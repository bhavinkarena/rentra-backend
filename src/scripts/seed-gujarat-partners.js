const ALL_POOLS = [...(gujaratPhotos.pools || []), ...(seedPhotos.pool || [])];
const ALL_VILLAS = [...(gujaratPhotos.villas || []), ...(gujaratPhotos.grounds || [])];
const ALL_LAWNS = [...(gujaratPhotos.lawns || []), ...(seedPhotos.lawn || [])];
const ALL_ROOMS = [...(gujaratPhotos.rooms || []), ...(seedPhotos.room || [])];

function buildGallery(spec, index, areaName, cityName) {
  const pick = (arr, count, offset) => {
    if (!arr || !arr.length) return [];
    return Array.from({ length: count }, (_, i) => arr[(offset + i) % arr.length]);
  };

  const heroPhotos = spec.pool ? pick(ALL_POOLS, 2, index * 2) : pick(ALL_VILLAS, 2, index * 2);

  const roomPhotos = pick(ALL_ROOMS, spec.bedrooms >= 3 ? 2 : 1, index * 3);
  const lawnPhotos = pick(ALL_LAWNS, 1, index);
  const groundsPhotos = spec.pool ? pick(ALL_VILLAS, 1, index + 3) : pick(ALL_LAWNS, 1, index + 4);

  const rawUrls = [...heroPhotos, ...roomPhotos, ...lawnPhotos, ...groundsPhotos];

  return rawUrls.map((url, i) => {
    let alt = `${spec.title} in ${areaName}, ${cityName}`;
    if (i === 0) {
      alt = spec.pool
        ? `${spec.title} in ${areaName}, ${cityName} — private ${spec.pool} swimming pool and deck`
        : `${spec.title} in ${areaName}, ${cityName} — spacious ${spec.highlight.toLowerCase()}`;
    } else if (url.includes('room')) {
      alt = `Air-conditioned bedroom at ${spec.title}, ${areaName}`;
    } else if (url.includes('pool')) {
      alt = `Crystal clean swimming pool at ${spec.title}, ${areaName}`;
    } else if (url.includes('lawn')) {
      alt = `Manicured party lawn at ${spec.title}, ${areaName}`;
    } else {
      alt = `Exterior villa grounds at ${spec.title}, ${areaName}`;
    }
    return { url, alt };
  });
}

